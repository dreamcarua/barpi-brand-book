def main():
    tpl = open(os.path.join(HERE, "creators.tpl.html"), encoding="utf-8").read()
    details = "\n".join(
        f"<details><summary>{html.escape(q)}</summary><div>{html.escape(a)}</div></details>" for q, a in FAQ)
    ld = {"@context": "https://schema.org", "@graph": [
        {"@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in FAQ]},
        {"@type": "WebPage", "@id": "https://barpi.com.ua/blogeram/#webpage", "url": "https://barpi.com.ua/blogeram/",
         "name": "Співпраця з блогерами і UGC-авторами | Barpi", "inLanguage": "uk",
         "about": {"@id": "https://barpi.com.ua/#organization"}},
        {"@type": "Organization", "@id": "https://barpi.com.ua/#organization", "name": "Barpi", "url": "https://barpi.com.ua/",
         "email": "office@barpi.ua", "sameAs": ["https://www.instagram.com/barpi.ua/"]},
    ]}
    out = tpl.replace("<!--FAQ-->", details).replace(
        "<!--JSONLD-->", '<script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False) + "</script>")
    open(os.path.join(HERE, "creators.html"), "w", encoding="utf-8").write(out)
    print("creators.html", len(out), "bytes,", len(FAQ), "FAQ")


if __name__ == "__main__":
    main()
